import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { themeVars } from '../src/modules/Theme/lib/themeVars.ts'

// A snapshot of inir's palette for the CSS fallback used before the IPC theme arrives.
const dir = join(process.env.XDG_STATE_HOME || join(homedir(), '.local/state'), 'quickshell/user/generated')

const isHex = (s: string) => /^#[0-9a-f]{6}$/i.test(s)

function palette(): Record<string, string> {
  for (const name of ['app-palette.json', 'palette.json', 'colors.json']) {
    const path = join(dir, name)
    if (!existsSync(path)) continue
    const json = JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>
    const keep = Object.entries(json).filter((e): e is [string, string] => typeof e[1] === 'string' && isHex(e[1]))
    return Object.fromEntries(keep.map(([k, v]) => [k, v.toLowerCase()]))
  }
  throw new Error(`inir palette not found in ${dir}`)
}

const colors = palette()
const colorTxt = join(dir, 'color.txt')
const seedFile = existsSync(colorTxt) ? readFileSync(colorTxt, 'utf8').trim().toLowerCase() : ''
const seed = isHex(seedFile) ? seedFile : (colors.primary ?? '')
if (!isHex(seed)) throw new Error(`inir seed not found in ${dir}`)

const metaPath = join(dir, 'theme-meta.json')
const meta = existsSync(metaPath) ? (JSON.parse(readFileSync(metaPath, 'utf8')) as { mode?: string }) : {}
const mode = meta.mode === 'light' ? 'light' : 'dark'

const lines = Object.entries(themeVars({ seed, mode, colors })).map(([k, v]) => `  ${k}: ${v};`)
writeFileSync(
  'src/app/styles/tokens.css',
  `/* generated by scripts/gen-theme.ts from inir */\n:root {\n  color-scheme: ${mode};\n${lines.join('\n')}\n}\n`,
)
