const TOUR_SEEN_KEY = 'smartsubs.tourSeen'

/** The tour opens by itself on the first visit to the player, and never again by itself. */
export const tourUnseen = () => !localStorage.getItem(TOUR_SEEN_KEY)

export const markTourSeen = () => localStorage.setItem(TOUR_SEEN_KEY, '1')

